def main(path="tests/sample.xlsx", conflict=False):
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "عام"
    ws.append(["م", "السؤال", "الإجابة"])
    for i, (q, a) in enumerate(QA, 1):
        ws.append([i, q, a])
    if conflict:
        ws.append([99, "ما هي عاصمة جمهورية مصر العربية؟", "الإسكندرية"])
    ws2 = wb.create_sheet("اختياري")
    ws2.append(["السؤال", "أ", "ب", "ج", "د", "الإجابة الصحيحة"])
    for row in MCQ:
        ws2.append(list(row))
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    print("wrote", path)

if __name__ == "__main__":
    import sys
    main(*(sys.argv[1:2]), conflict="--conflict" in sys.argv)
